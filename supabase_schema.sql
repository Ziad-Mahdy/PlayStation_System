-- ==============================================================================
-- PlayStation Cafe - Supabase Database Schema (مع نظام الاشتراكات والعملاء)
-- ==============================================================================

-- 1. جدول الاشتراكات والعملاء (Subscriptions & Clients)
CREATE TABLE IF NOT EXISTS public.subscriptions (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    client_name TEXT NOT NULL,
    shop_name TEXT NOT NULL,
    phone TEXT NOT NULL UNIQUE,
    code TEXT NOT NULL UNIQUE,
    duration_days INTEGER NOT NULL DEFAULT 30,
    is_active BOOLEAN DEFAULT false,       -- هل قام العميل بتسجيل الدخول وتفعيل الكود
    is_suspended BOOLEAN DEFAULT false,    -- هل تم إيقاف الاشتراك يدوياً من المطور
    admin_password TEXT NOT NULL DEFAULT 'Admin@123', -- باسوورد لوحة تحكم الأدمن الخاصة بالعميل
    activated_at TIMESTAMPTZ DEFAULT NULL, -- توقيت التفعيل الفعلي (يبدأ العد من لحظته)
    expires_at TIMESTAMPTZ DEFAULT NULL,   -- تاريخ ووقت الانتهاء المحسوب بدقة
    notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. جدول الأجهزة (Devices)
CREATE TABLE IF NOT EXISTS public.devices (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    client_phone TEXT NOT NULL DEFAULT 'default',
    name TEXT NOT NULL,
    type TEXT NOT NULL DEFAULT 'PlayStation 5',
    is_vip BOOLEAN DEFAULT false,
    single_price NUMERIC(10, 2) DEFAULT 45.00,
    multi_price NUMERIC(10, 2) DEFAULT 35.00,
    status TEXT DEFAULT 'free', -- 'free' | 'busy'
    session JSONB DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_device_per_client UNIQUE (client_phone, name)
);

-- إضافة عمود client_phone في حال كان الجدول موجوداً مسبقاً
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='devices' AND column_name='client_phone') THEN
    ALTER TABLE public.devices ADD COLUMN client_phone TEXT NOT NULL DEFAULT 'default';
  END IF;
END $$;

-- 3. جدول فئات الصالة (Categories)
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    client_phone TEXT NOT NULL DEFAULT 'default',
    name TEXT NOT NULL,
    CONSTRAINT unique_category_per_client UNIQUE (client_phone, name)
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='categories' AND column_name='client_phone') THEN
    ALTER TABLE public.categories ADD COLUMN client_phone TEXT NOT NULL DEFAULT 'default';
  END IF;
END $$;

-- 4. جدول البوفيه والمشروبات (Products)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    client_phone TEXT NOT NULL DEFAULT 'default',
    name TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    category TEXT DEFAULT 'مشروبات',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT unique_product_per_client UNIQUE (client_phone, name)
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='products' AND column_name='client_phone') THEN
    ALTER TABLE public.products ADD COLUMN client_phone TEXT NOT NULL DEFAULT 'default';
  END IF;
END $$;

-- 5. جدول سجل الفواتير المنتهية (Completed Invoices)
CREATE TABLE IF NOT EXISTS public.completed_sessions (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    client_phone TEXT NOT NULL DEFAULT 'default',
    device_name TEXT NOT NULL,
    device_type TEXT,
    is_vip BOOLEAN DEFAULT false,
    customer_name TEXT DEFAULT '',
    start_time BIGINT NOT NULL,
    end_time BIGINT NOT NULL,
    duration_seconds INTEGER NOT NULL,
    mode TEXT NOT NULL,
    time_type TEXT DEFAULT 'open',
    target_minutes INTEGER DEFAULT NULL,
    time_cost NUMERIC(10, 2) NOT NULL,
    orders_cost NUMERIC(10, 2) DEFAULT 0.00,
    total NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='completed_sessions' AND column_name='client_phone') THEN
    ALTER TABLE public.completed_sessions ADD COLUMN client_phone TEXT NOT NULL DEFAULT 'default';
  END IF;
END $$;

-- تمكين سياسات الأمان (Row Level Security)
ALTER TABLE public.subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.completed_sessions ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public access on subscriptions') THEN
    CREATE POLICY "Allow public access on subscriptions" ON public.subscriptions FOR ALL USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public access on devices') THEN
    CREATE POLICY "Allow public access on devices" ON public.devices FOR ALL USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public access on categories') THEN
    CREATE POLICY "Allow public access on categories" ON public.categories FOR ALL USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public access on products') THEN
    CREATE POLICY "Allow public access on products" ON public.products FOR ALL USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public access on completed_sessions') THEN
    CREATE POLICY "Allow public access on completed_sessions" ON public.completed_sessions FOR ALL USING (true) WITH CHECK (true);
  END IF;
END $$;

-- تمكين المزامنة اللحظية (Realtime)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE public.subscriptions; EXCEPTION WHEN duplicate_object THEN END;
    BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE public.devices; EXCEPTION WHEN duplicate_object THEN END;
    BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE public.categories; EXCEPTION WHEN duplicate_object THEN END;
    BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE public.products; EXCEPTION WHEN duplicate_object THEN END;
    BEGIN ALTER PUBLICATION supabase_realtime ADD TABLE public.completed_sessions; EXCEPTION WHEN duplicate_object THEN END;
  END IF;
END $$;
