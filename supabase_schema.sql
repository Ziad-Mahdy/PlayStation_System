-- 1. جدول الأجهزة (Devices)
CREATE TABLE IF NOT EXISTS public.devices (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL UNIQUE,
    type TEXT NOT NULL DEFAULT 'PlayStation 5',
    is_vip BOOLEAN DEFAULT false,
    single_price NUMERIC(10, 2) DEFAULT 45.00,
    multi_price NUMERIC(10, 2) DEFAULT 35.00,
    status TEXT DEFAULT 'free', -- 'free' | 'busy'
    session JSONB DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. جدول فئات الصالة (Categories)
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT UNIQUE NOT NULL
);

-- 3. جدول البوفيه والمشروبات (Products)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT UNIQUE NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    category TEXT DEFAULT 'مشروبات',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. جدول سجل الفواتير المنتهية (Completed Invoices)
CREATE TABLE IF NOT EXISTS public.completed_sessions (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    device_name TEXT NOT NULL,
    device_type TEXT,
    is_vip BOOLEAN DEFAULT false,
    customer_name TEXT DEFAULT '',
    start_time BIGINT NOT NULL,
    end_time BIGINT NOT NULL,
    duration_seconds INTEGER NOT NULL,
    mode TEXT NOT NULL,
    time_type TEXT DEFAULT 'open',
    target_minutes INTEGER DEFAULT NULL,
    time_cost NUMERIC(10, 2) NOT NULL,
    orders_cost NUMERIC(10, 2) DEFAULT 0.00,
    total NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- تمكين سياسات الأمان (Row Level Security) للسماح بالقراءة والتعديل من تطبيق الكافيه
ALTER TABLE public.devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.completed_sessions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public access on devices" ON public.devices FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public access on categories" ON public.categories FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public access on products" ON public.products FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public access on completed_sessions" ON public.completed_sessions FOR ALL USING (true) WITH CHECK (true);

-- تمكين المزامنة اللحظية المباشرة (Realtime)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    BEGIN
      ALTER PUBLICATION supabase_realtime ADD TABLE public.devices;
    EXCEPTION WHEN duplicate_object THEN END;
    BEGIN
      ALTER PUBLICATION supabase_realtime ADD TABLE public.categories;
    EXCEPTION WHEN duplicate_object THEN END;
    BEGIN
      ALTER PUBLICATION supabase_realtime ADD TABLE public.products;
    EXCEPTION WHEN duplicate_object THEN END;
    BEGIN
      ALTER PUBLICATION supabase_realtime ADD TABLE public.completed_sessions;
    EXCEPTION WHEN duplicate_object THEN END;
  END IF;
END $$;

